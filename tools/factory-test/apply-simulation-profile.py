# 行序 → (种类, 序号)
# kind 之一：float/double/int32/uint32/int16/u16/int64/u64/in_float/in_int32/in_u16/bool
# 注意：float 序号为全局累加（0..14），使 3 个块各取 5 个不同的过程量；
#       小整数/计数器/双精度按块取序（int16/u16 每块 2 个 → 6 个全部用到）。
ROW_KIND = []
_float_idx = 0
for _block in range(3):
    for _i in range(5):
        ROW_KIND.append(("float", _float_idx))
        _float_idx += 1
    ROW_KIND.append(("int32", _block))
    ROW_KIND.append(("uint32", _block))
    ROW_KIND.append(("int16", _block * 2))
    ROW_KIND.append(("u16", _block * 2))
    ROW_KIND.append(("int16", _block * 2 + 1))
    ROW_KIND.append(("u16", _block * 2 + 1))
    ROW_KIND.append(("double", _block))
    ROW_KIND.append(("int64", _block))
    ROW_KIND.append(("uint64", _block))
ROW_KIND += [
    ("in_float", 0),
    ("in_int32", 0),
    ("in_u16", 0),
    ("in_u16", 1),
    ("bool", 0),
    ("bool", 1),
    ("bool", 2),
    ("bool", 3),
]


def _fmt(x):
    """数值格式化：整数值不带小数位，其余去掉多余 0。"""
    if isinstance(x, float) and x.is_integer():
        return str(int(x))
    return repr(x) if isinstance(x, float) else str(x)


def _row_values(kind, idx, prof):
    """返回 (Deadband, ScaleFactor, ScaleOffset, MinValue, MaxValue)。"""
    if kind == "bool":
        return ("0", "1", "0", "0", "1")
    if kind in ("float", "double"):
        emin, emax, db = prof["floats"][idx] if kind == "float" else prof["doubles"][idx]
        return (_fmt(db), "1", "0", _fmt(emin), _fmt(emax))
    if kind in ("int32", "uint32"):
        key = kind
        emin, emax = prof[key][idx]
        return ("1", "1", "0", _fmt(emin), _fmt(emax))
    if kind in ("int64", "uint64"):
        key = kind
        emin, emax = prof[key][idx]
        return ("1", "1", "0", _fmt(emin), _fmt(emax))
    if kind == "int16":
        rmin, rmax, sf = prof["int16_raw"][idx]
        return (_fmt(_db(sf)), _fmt(sf), "0", _fmt(rmin), _fmt(rmax))
    if kind == "u16":
        rmin, rmax, sf = prof["uint16_raw"][idx]
        return (_fmt(_db(sf)), _fmt(sf), "0", _fmt(rmin), _fmt(rmax))
    if kind == "in_float":
        emin, emax, db = prof["in_float"]
        return (_fmt(db), "1", "0", _fmt(emin), _fmt(emax))
    if kind == "in_int32":
        emin, emax = prof["in_int32"]
        return ("1", "1", "0", _fmt(emin), _fmt(emax))
    if kind == "in_u16":
        tup = prof["in_uint16"][idx]
        rmin, rmax, sf = tup[0], tup[1], tup[2]
        so = tup[3] if len(tup) == 4 else 0
        return (_fmt(_db(sf)), _fmt(sf), _fmt(so), _fmt(rmin), _fmt(rmax))
    raise ValueError(kind)


HEADER = "Name,Address,DataType,Access,Enabled,ScanIntervalMs,Deadband,ScaleFactor,ScaleOffset,Description,MinValue,MaxValue"


def build_unit_csv(unit_id, prof):
    """读取原始 CSV，覆盖 3 列 + 追加 Min/Max，返回新 CSV 文本。"""
    src = BASE / f"points-device-{unit_id:02d}.csv"
    text = src.read_bytes().decode("utf-8")
    rows = list(csv.reader(io.StringIO(text)))
    assert rows[0][:10] == HEADER.split(",")[:10], rows[0]
    out = [HEADER]
    for r in range(1, len(rows)):
        row = list(rows[r])
        if len(row) < 10:
            row = row + [""] * (10 - len(row))
        kind, idx = ROW_KIND[r - 1]
        db, sf, so, mn, mx = _row_values(kind, idx, prof)
        row[6], row[7], row[8] = db, sf, so
        out.append(",".join(row[:10] + [mn, mx]))
    return "\r\n".join(out) + "\r\n"


def main():
    for unit_id in range(1, 11):
        prof = PROFILES[unit_id]
        assert prof["name"] in (BASE / f"points-device-{unit_id:02d}.csv").read_bytes().decode("utf-8")
        csv_text = build_unit_csv(unit_id, prof)
        dest = BASE / f"points-device-{unit_id:02d}.csv"
        dest.write_bytes(csv_text.encode("utf-8"))  # 无 BOM
        print(f"{dest.name}: 已生成（{len(csv_text.splitlines()) - 1} 点，{len(csv_text.encode('utf-8'))} bytes）")


if __name__ == "__main__":
    main()
