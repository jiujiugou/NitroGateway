"""
apply-simulation-profile.py

为 factory-test 的 10 台设备点位 CSV 生成"真实感模拟"配置。

背景：ModbusSlaveSim 按 CSV 里的 MinValue/MaxValue（若存在）每 1s 生成随机原始值，
网关注入同一 CSV 后按 Deadband/ScaleFactor/ScaleOffset 做工程缩放与死区抑制：
    engValue = raw * ScaleFactor + ScaleOffset
    死区：|eng - last| < Deadband 时抑制写入（ADR-053），Deadband 单位 = 工程值。

本脚本的差异化规则（按 设备名称 / 地址区 / 数据类型）：
  * Bool（C01/C02 线圈、D01/D02 离散输入）：不缩放（sf=1, so=0），无死区（db=0），波段 0~1。
  * Int16/UInt16（保持寄存器内的小整数槽位）：按 "1 位小数" 存原始计数，sf=0.1（个别 0.01/0.001），
    db = 5 个原始计数（即 5*sf 工程单位），过滤小幅抖动。
  * Int32/UInt32/Int64/UInt64（累计量/计数器）：sf=1, so=0，db=1（每 1 个计数都算变化）。
  * Float/Double（过程量）：raw 即工程值（sf=1, so=0），db 按各物理量测量精度显式给定。
  * 设备类型差异：每台设备的 15 个 Float 槽位、计数器、小整数槽位按该设备的真实物理量
    赋值（空压机=压力/温度、变频器=Hz/A/V、冷水机组=水温/压力、锅炉=汽温/汽压/水位、
    注塑机=料筒温度/射胶压力、风机=转速/风量/振动、水泵=流量/扬程、电表=电压/电流/功率）。

文件格式：保留网关导出兼容的 10 列（Name..Description），末尾追加模拟器专用 MinValue/MaxValue。
网关 ParseCsv / 模拟器 LoadCsv 均按列名取用，多余列被忽略——因此 12 列对两方都兼容。

用法：python apply-simulation-profile.py
"""

